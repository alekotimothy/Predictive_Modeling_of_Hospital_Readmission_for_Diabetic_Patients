"""Feature Engineering"""

# Separate features
categorical = df.select_dtypes(include='object').columns.tolist()
# 'readmitted' was encoded to numerical, so it's not in categorical
# categorical.remove('readmitted') # This line caused the error

numerical = df.select_dtypes(exclude='object').columns.tolist()
# Remove 'readmitted' from the numerical list
numerical.remove('readmitted')

# Custom encoding: One-hot for low cardinality; Target encoding for diagnoses
low_card = [col for col in categorical if df[col].nunique() < 50 and 'diag' not in col]
high_card = ['diag_1', 'diag_2', 'diag_3']

# Define transformers
preprocessor = ColumnTransformer([
    ('target', ce.TargetEncoder(), high_card),
    ('onehot', ce.OneHotEncoder(use_cat_names=True), low_card),
    ('scale', StandardScaler(), numerical)
])

